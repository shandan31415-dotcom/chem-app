def match_keys(name):
    """生成资讯匹配关键词：全名 + 去掉省市前缀与通用后缀的核心名"""
    keys = [name]
    core = name
    for p in ("中国石化", "中石化", "山东", "淄博", "东营", "青岛", "烟台", "潍坊",
              "济宁", "泰安", "威海", "日照", "临沂", "德州", "聊城", "滨州",
              "菏泽", "枣庄", "济南", "蓬莱"):
        if core.startswith(p) and len(core) - len(p) >= 3:
            core = core[len(p):]
    for s in ("有限公司", "股份有限公司", "集团", "股份", "控股", "化工", "新材料", "科技", "新技术"):
        if core.endswith(s) and len(core) - len(s) >= 3:
            core = core[:-len(s)]
    if core != name and len(core) >= 3:
        keys.append(core)
    return keys


def to_ent(t):
    name, products, cats, high, note = t[0], t[1], t[2], t[3], t[4]
    verify = bool(t[5]) if len(t) > 5 else False
    e = {
        "name": name,
        "match": match_keys(name),
        "products": products,
        "cats": [c.strip() for c in cats.split(",") if c.strip()],
        "high": bool(high),
        "note": note,
    }
    if verify:
        e["verify"] = True
    return e
